#!/usr/bin/env node
// Generates engine/src/tests/ReferenceData.h from the app's TypeScript sources, so the native
// self-test compares against the exact Web Audio engine formulas.
//
//   node --experimental-transform-types --no-warnings \
//        --import ./engine/tests/tools/ts-hooks.mjs engine/tests/tools/gen-reference.mjs
//
// (run from projects/mad-studio; needs Node >= 22.15, no npm packages)
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '../../..');
const src = (p) => `${app}/src/${p}`;

const { envelopeValue } = await import(src('audio/envelope.ts'));
const { makeImpulseResponse } = await import(src('audio/effects/effects.ts'));
const { Scheduler, swingOffsetTicks } = await import(src('audio/scheduler.ts'));
const { encodeWav } = await import(src('audio/wav.ts'));
const { volumeToGain, midiToHz, PPQ } = await import(src('model/timing.ts'));
const { DELAY_DIVISION_BEATS } = await import(src('model/effects.ts'));

const lines = [];
const out = (s = '') => lines.push(s);
const num = (v) => {
  if (!Number.isFinite(v)) throw new Error(`non-finite reference value ${v}`);
  const s = v.toPrecision(17);
  return s.includes('e') || s.includes('.') ? s : `${s}.0`;
};
const arr = (name, values, type = 'double') => {
  out(`inline constexpr ${type} ${name}[] = {`);
  for (let i = 0; i < values.length; i += 4) out(`    ${values.slice(i, i + 4).map(num).join(', ')},`);
  out('};');
};

out('// Generated by engine/tests/tools/gen-reference.mjs from the TypeScript sources in src/.');
out('// Do not edit by hand; re-run the generator instead.');
out('#pragma once');
out('');
out('namespace mad::reference');
out('{');

// ---- envelope.ts ---------------------------------------------------------------------------
const envs = [
  { attack: 0.1, decay: 0.4, sustain: 0.5, release: 0.2 },
  { attack: 0.0, decay: 0.0, sustain: 0.3, release: 0.0 },
  { attack: 0.002, decay: 0.35, sustain: 0, release: 0.25 },
  { attack: 0.6, decay: 1.0, sustain: 0.8, release: 1.2 },
];
const envTimes = [0, 0.0005, 0.001, 0.0015, 0.002, 0.01, 0.05, 0.1, 0.2, 0.35, 0.6, 1, 2, 5];
out('struct EnvelopeCase { double attack, decay, sustain, release, base, peak; };');
out('inline constexpr EnvelopeCase envelopeCases[] = {');
const envCases = [];
envs.forEach((e) => {
  for (const [base, peak] of [[0, 1], [0, 0.78], [0.2, 0.9]]) envCases.push({ ...e, base, peak });
});
for (const c of envCases) out(`    { ${[c.attack, c.decay, c.sustain, c.release, c.base, c.peak].map(num).join(', ')} },`);
out('};');
arr('envelopeTimes', envTimes);
const envValues = [];
for (const c of envCases) for (const t of envTimes) envValues.push(envelopeValue(c, c.base, c.peak, t));
arr('envelopeValues', envValues);
out('');

// ---- model/timing.ts -----------------------------------------------------------------------
const vols = [0, 0.1, 0.5, 0.62, 0.8, 0.92, 1];
arr('volumePositions', vols);
arr('volumeGains', vols.map(volumeToGain));
const keys = [0, 21, 45, 60, 69, 76, 127];
arr('midiKeys', keys);
arr('midiHz', keys.map(midiToHz));
arr('delayDivisionBeats', DELAY_DIVISION_BEATS);
out('');

// ---- scheduler.ts: swing and timing ----------------------------------------------------------
const swingTicks = [0, 12, 24, 36, 48, 72, 96, 120, 168];
const swings = [0, 0.12, 0.5, 1];
arr('swingTicks', swingTicks);
arr('swingAmounts', swings);
const swingValues = [];
for (const s of swings) for (const t of swingTicks) swingValues.push(swingOffsetTicks(t, s));
arr('swingOffsets', swingValues);

// Look-ahead scheduler reference: events + loop wrap + swing at 120 BPM over 4.5 s.
const tlEvents = [0, 24, 48, 72, 96, 132, 200, 360].map((tick) => ({ tick, length: 24, channelId: 'c', key: 60, velocity: 1 }));
const timeline = { events: tlEvents, start: 0, end: PPQ * 4 };
const fired = [];
const state = { now: 0 };
const sched = new Scheduler({
  now: () => state.now,
  timeline: () => timeline,
  bpm: () => 120,
  swing: () => 0.5,
  beatsPerBar: () => 4,
  onEvent: (e, time) => fired.push([e.tick, time]),
});
sched.start(0, 0);
for (let t = 0; t <= 4.5; t += 0.02) {
  state.now = t;
  sched.pump();
}
const kept = fired.filter(([, time]) => time < 4.4);
arr('schedulerEventTicks', tlEvents.map((e) => e.tick));
arr('schedulerFiredTicks', kept.map(([tick]) => tick));
arr('schedulerFiredTimes', kept.map(([, time]) => time));
out('inline constexpr double schedulerBpm = 120.0, schedulerSwing = 0.5, schedulerLoopEnd = 384.0, schedulerSeconds = 4.4;');
out('');

// ---- effects.ts: impulse response --------------------------------------------------------------
const irCases = [
  [48000, 2.2, 0.5],
  [44100, 1.2, 0.5],
  [48000, 3.2, 0.0],
];
out('struct ImpulseCase { double sampleRate, decay, damping; int length; double normScale; };');
out('inline constexpr ImpulseCase impulseCases[] = {');
const irHeads = [];
for (const [sr, decay, damping] of irCases) {
  const [l, r] = makeImpulseResponse(sr, decay, damping);
  // Web Audio ConvolverNode normalisation (Chromium Reverb::CalculateNormalizationScale).
  let power = 0;
  for (const ch of [l, r]) for (let i = 0; i < ch.length; i++) power += ch[i] * ch[i];
  power = Math.sqrt(power / (2 * l.length));
  if (!Number.isFinite(power) || power < 0.000125) power = 0.000125;
  const scale = (1 / power) * Math.pow(10, -58 / 20) * (44100 / sr);
  out(`    { ${num(sr)}, ${num(decay)}, ${num(damping)}, ${l.length}, ${num(scale)} },`);
  irHeads.push(Array.from(l.slice(0, 48)), Array.from(r.slice(0, 48)), Array.from(l.slice(l.length - 8)));
}
out('};');
irHeads.forEach((v, i) => arr(`impulseHead${i}`, v, 'float'));
out('inline constexpr const float* impulseHeads[] = {');
irHeads.forEach((_, i) => out(`    impulseHead${i},`));
out('};');
out('');

// ---- wav.ts: byte-exact encoder output (16-bit uses TPDF dither from a fixed LCG) --------------
const sig = [new Float32Array(12), new Float32Array(12)];
for (let i = 0; i < 12; i++) {
  sig[0][i] = Math.sin(i * 0.7) * 0.8;
  sig[1][i] = i === 5 ? 1.5 : i === 6 ? -1.25 : Math.cos(i * 0.3) * 0.5;
}
arr('wavSignalL', Array.from(sig[0]), 'float');
arr('wavSignalR', Array.from(sig[1]), 'float');
for (const bits of [16, 24, 32]) {
  const bytes = encodeWav(sig, 48000, bits);
  out(`inline constexpr unsigned char wavBytes${bits}[] = {`);
  for (let i = 0; i < bytes.length; i += 16) out(`    ${Array.from(bytes.slice(i, i + 16)).join(', ')},`);
  out('};');
}
out('');

// ---- Web Audio BiquadFilterNode coefficients (spec formulas, computed independently) ------------
const sr = 48000;
const biquad = (type, f, Q, gain) => {
  const nyq = sr / 2;
  const fn = Math.min(Math.max(f / nyq, 0), 1);
  const w0 = Math.PI * fn;
  const cos = Math.cos(w0);
  const sin = Math.sin(w0);
  const A = Math.pow(10, gain / 40);
  let b0, b1, b2, a0, a1, a2;
  switch (type) {
    case 'lowpass': {
      const alpha = sin / (2 * Math.pow(10, Q / 20));
      b0 = (1 - cos) / 2; b1 = 1 - cos; b2 = (1 - cos) / 2; a0 = 1 + alpha; a1 = -2 * cos; a2 = 1 - alpha;
      break;
    }
    case 'highpass': {
      const alpha = sin / (2 * Math.pow(10, Q / 20));
      b0 = (1 + cos) / 2; b1 = -(1 + cos); b2 = (1 + cos) / 2; a0 = 1 + alpha; a1 = -2 * cos; a2 = 1 - alpha;
      break;
    }
    case 'bandpass': {
      const alpha = sin / (2 * Q);
      b0 = alpha; b1 = 0; b2 = -alpha; a0 = 1 + alpha; a1 = -2 * cos; a2 = 1 - alpha;
      break;
    }
    case 'notch': {
      const alpha = sin / (2 * Q);
      b0 = 1; b1 = -2 * cos; b2 = 1; a0 = 1 + alpha; a1 = -2 * cos; a2 = 1 - alpha;
      break;
    }
    case 'peaking': {
      const alpha = sin / (2 * Q);
      b0 = 1 + alpha * A; b1 = -2 * cos; b2 = 1 - alpha * A; a0 = 1 + alpha / A; a1 = -2 * cos; a2 = 1 - alpha / A;
      break;
    }
    case 'lowshelf': {
      const alpha = (sin / 2) * Math.sqrt(2);
      const k = 2 * Math.sqrt(A) * alpha;
      b0 = A * (A + 1 - (A - 1) * cos + k); b1 = 2 * A * (A - 1 - (A + 1) * cos); b2 = A * (A + 1 - (A - 1) * cos - k);
      a0 = A + 1 + (A - 1) * cos + k; a1 = -2 * (A - 1 + (A + 1) * cos); a2 = A + 1 + (A - 1) * cos - k;
      break;
    }
    case 'highshelf': {
      const alpha = (sin / 2) * Math.sqrt(2);
      const k = 2 * Math.sqrt(A) * alpha;
      b0 = A * (A + 1 + (A - 1) * cos + k); b1 = -2 * A * (A - 1 + (A + 1) * cos); b2 = A * (A + 1 + (A - 1) * cos - k);
      a0 = A + 1 - (A - 1) * cos + k; a1 = 2 * (A - 1 - (A + 1) * cos); a2 = A + 1 - (A - 1) * cos - k;
      break;
    }
  }
  return [b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0];
};
const types = ['lowpass', 'highpass', 'bandpass', 'notch', 'peaking', 'lowshelf', 'highshelf'];
const bqCases = [
  [1800, 4, 0],
  [420, 3, 0],
  [8000, 1, 0],
  [150, 0.7, 6],
  [1000, 0.9, -6],
  [6000, 18, 12],
];
out('struct BiquadCase { int type; double frequency, q, gain; double b0, b1, b2, a1, a2; };');
out('// type: 0 lowpass, 1 highpass, 2 bandpass, 3 notch, 4 peaking, 5 lowshelf, 6 highshelf; sample rate 48000');
out('inline constexpr BiquadCase biquadCases[] = {');
types.forEach((t, ti) => {
  for (const [f, Q, g] of bqCases) out(`    { ${ti}, ${num(f)}, ${num(Q)}, ${num(g)}, ${biquad(t, f, Q, g).map(num).join(', ')} },`);
});
out('};');
out('');

out('} // namespace mad::reference');
out('');

const target = resolve(here, '../../src/tests/ReferenceData.h');
writeFileSync(target, lines.join('\n'));
console.log(`wrote ${target}`);
